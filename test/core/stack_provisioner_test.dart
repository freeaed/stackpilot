import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:stackpilot/core/bundled_payload.dart';
import 'package:stackpilot/core/component_catalog.dart';
import 'package:stackpilot/core/ini.dart';
import 'package:stackpilot/core/stack_bootstrap.dart';
import 'package:stackpilot/core/stack_layout.dart';
import 'package:stackpilot/core/stack_provisioner.dart';

void main() {
  late Directory temp;
  late StackLayout layout;
  late List<StackComponent> installCalls;
  late List<(String executable, List<String> arguments)> commands;

  setUp(() {
    temp = Directory.systemTemp.createTempSync('stackpilot_provision_');
    layout = StackBootstrap.create(
      root: p.join(temp.path, 'stack'),
      postgresqlPort: 5433,
    );
    installCalls = [];
    commands = [];
  });

  tearDown(() {
    if (temp.existsSync()) {
      temp.deleteSync(recursive: true);
    }
  });

  StackInstall createInstall(
    StackComponent component,
    String installName,
  ) {
    installCalls.add(component);
    final directory = p.join(
      layout.root,
      'bin',
      component.directoryName,
      installName,
    );
    final executable = StackLayout.executablePath(component, directory);
    File(executable).createSync(recursive: true);

    switch (component) {
      case StackComponent.apache:
        File(p.join(directory, 'conf', 'httpd.conf'))
          ..createSync(recursive: true)
          ..writeAsStringSync('''
ServerRoot "C:/Apache24"
Listen 80
DocumentRoot "C:/Apache24/htdocs"
<Directory "C:/Apache24/htdocs">
    Require all granted
</Directory>
''');
        File(
          p.join(directory, 'modules', 'mod_mpm_winnt.so'),
        ).createSync(recursive: true);
      case StackComponent.php:
        File(p.join(directory, 'php8apache2_4.dll')).createSync();
        File(p.join(directory, 'libcrypto-3-x64.dll')).createSync();
        File(p.join(directory, 'libssl-3-x64.dll')).createSync();
      case StackComponent.mysql:
        File(p.join(directory, 'bin', 'mysql_install_db.exe')).createSync();
      case StackComponent.postgresql:
        File(p.join(directory, 'bin', 'initdb.exe')).createSync();
      case StackComponent.redis:
        File(
          p.join(directory, 'redis.windows.conf'),
        ).writeAsStringSync('port 6379\nbind 127.0.0.1\ndir ./\n');
      case StackComponent.nginx:
      case StackComponent.nodejs:
      case StackComponent.memcached:
      case StackComponent.mailpit:
        break;
    }

    return StackInstall(
      component: component,
      version: installName,
      directory: directory,
      executablePath: executable,
    );
  }

  StackProvisioner createProvisioner({
    ProvisionDigest? digest,
    ProvisionInstall? installArchive,
  }) {
    return StackProvisioner(
      layout,
      download: (uri, file, onProgress) async {
        // The fake download records the URL so the fake digest can pick the
        // right release checksum.
        file.writeAsStringSync(uri.toString());
        onProgress(7, 7);
      },
      digest:
          digest ??
          (file) async {
            final url = file.readAsStringSync();
            return ComponentCatalog.releases
                .firstWhere((release) => release.url == url)
                .sha256;
          },
      installArchive:
          installArchive ??
          (component, archivePath, installName) async =>
              createInstall(component, installName),
      run: (executable, arguments, workingDirectory) async {
        commands.add((executable, arguments));
        if (executable.endsWith('initdb.exe')) {
          final index = arguments.indexOf('-D');
          final dataDirectory = arguments[index + 1];
          Directory(dataDirectory).createSync(recursive: true);
          File(
            p.join(dataDirectory, 'PG_VERSION'),
          ).writeAsStringSync('17');
          File(
            p.join(dataDirectory, 'postgresql.conf'),
          ).writeAsStringSync('# generated by initdb\nport = 5432\n');
        }
        return 0;
      },
    );
  }

  test('installs MariaDB with a stack-local data directory', () async {
    final release = ComponentCatalog.mariadb;
    final progress = <ProvisionProgress>[];

    final result = await createProvisioner().install(
      release,
      onProgress: progress.add,
    );

    expect(result.install.version, release.installName);
    expect(result.alreadyInstalled, isFalse);
    expect(result.activated, isTrue);

    final dataDirectory = p.join(layout.root, 'data', 'mysql');
    expect(Directory(dataDirectory).existsSync(), isTrue);

    final ini = File(
      p.join(result.install.directory, 'my.ini'),
    ).readAsStringSync();
    expect(
      ini,
      contains('basedir="${result.install.directory.replaceAll('\\', '/')}"'),
    );
    expect(ini, contains('datadir="${dataDirectory.replaceAll('\\', '/')}"'));
    expect(ini, contains('port=3306'));
    expect(ini, contains('[client]'));

    expect(commands, hasLength(1));
    expect(commands.single.$1, endsWith('mysql_install_db.exe'));
    expect(commands.single.$2, contains('--datadir=$dataDirectory'));
    expect(commands.single.$2, contains('--port=3306'));

    final profile = File(
      p.join(layout.root, 'usr', 'profile', 'default.ini'),
    ).readAsStringSync();
    expect(profile, contains('Version=${release.installName}'));

    final marker = IniDocument.parse(File(layout.markerPath).readAsStringSync());
    expect(marker.value('mysql', 'Use'), '-1');

    expect(
      progress.map((entry) => entry.phase),
      containsAllInOrder([
        ProvisionPhase.downloading,
        ProvisionPhase.verifying,
        ProvisionPhase.installing,
        ProvisionPhase.configuring,
        ProvisionPhase.done,
      ]),
    );
    expect(
      progress.any(
        (entry) =>
            entry.phase == ProvisionPhase.downloading && entry.fraction == 1.0,
      ),
      isTrue,
    );
  });

  test('rejects an archive whose checksum does not match', () async {
    final release = ComponentCatalog.php;
    var installed = false;

    final provisioner = StackProvisioner(
      layout,
      download: (uri, file, onProgress) async {
        file.writeAsStringSync('tampered');
      },
      digest: (_) async => List.filled(64, '0').join(),
      installArchive: (component, archivePath, installName) async {
        installed = true;
        return createInstall(component, installName);
      },
    );

    await expectLater(
      provisioner.install(release),
      throwsA(
        isA<ProvisionException>().having(
          (error) => error.message,
          'message',
          contains('checksum'),
        ),
      ),
    );
    expect(installed, isFalse);
    expect(installCalls, isEmpty);
  });

  test('installs PHP before Apache so mod_php is included', () async {
    final report = await createProvisioner().installAll([
      ComponentCatalog.apache,
      ComponentCatalog.php,
    ]);

    expect(report.ok, isTrue);
    expect(report.installed, hasLength(2));
    expect(installCalls, [StackComponent.php, StackComponent.apache]);

    final php = report.installed
        .firstWhere((item) => item.release == ComponentCatalog.php)
        .install;
    final apache = report.installed
        .firstWhere((item) => item.release == ComponentCatalog.apache)
        .install;

    final modPhp = File(
      p.join(layout.root, 'etc', 'apache2', 'mod_php.conf'),
    );
    expect(modPhp.existsSync(), isTrue);
    expect(
      modPhp.readAsStringSync(),
      contains(
        'LoadModule php_module "${php.directory.replaceAll('\\', '/')}',
      ),
    );

    final httpd = File(
      p.join(apache.directory, 'conf', 'httpd.conf'),
    ).readAsStringSync();
    expect(
      httpd,
      contains('ServerRoot "${apache.directory.replaceAll('\\', '/')}"'),
    );
    expect(
      httpd,
      contains('DocumentRoot "${layout.documentRoot.replaceAll('\\', '/')}"'),
    );
    expect(httpd, contains('mod_php.conf'));
    expect(httpd, contains('ServerName localhost'));

    final vhost = File(
      p.join(
        layout.root,
        'etc',
        'apache2',
        'sites-enabled',
        '00-default.conf',
      ),
    );
    expect(vhost.existsSync(), isTrue);
    expect(vhost.readAsStringSync(), contains('DocumentRoot'));

    final profile = File(
      p.join(layout.root, 'usr', 'profile', 'default.ini'),
    ).readAsStringSync();
    expect(profile, contains('Version=${ComponentCatalog.php.installName}'));
    expect(
      profile,
      contains('Version=${ComponentCatalog.apache.installName}'),
    );
  });

  test('generates an nginx config for this stack', () async {
    final release = ComponentCatalog.nginx;
    final result = await createProvisioner().install(release);

    final config = File(
      p.join(result.install.directory, 'conf', 'nginx.conf'),
    ).readAsStringSync();
    expect(config, contains('Generated by StackPilot'));
    expect(
      config,
      contains('root "${layout.documentRoot.replaceAll('\\', '/')}"'),
    );
    expect(config, contains('include conf/mime.types;'));
    expect(config, contains('fastcgi_pass 127.0.0.1:9000;'));

    // Nginx is enabled when it is the only web server in the stack.
    final marker = IniDocument.parse(File(layout.markerPath).readAsStringSync());
    expect(marker.value('nginx', 'Use'), '-1');
  });

  test('generates a redis config with a stack-local data folder', () async {
    final release = ComponentCatalog.redis;
    final result = await createProvisioner().install(release);

    final dataDirectory = p.join(layout.root, 'data', 'redis');
    expect(Directory(dataDirectory).existsSync(), isTrue);

    final config = File(
      p.join(result.install.directory, 'redis.conf'),
    ).readAsStringSync();
    expect(config, contains('Generated by StackPilot'));
    expect(
      config,
      contains('dir "${dataDirectory.replaceAll('\\', '/')}"'),
    );
    expect(config, contains('bind 127.0.0.1'));
  });

  test('initialises PostgreSQL once and writes the stack port', () async {
    final release = ComponentCatalog.postgresql;
    final provisioner = createProvisioner();

    final result = await provisioner.install(release);

    expect(commands, hasLength(1));
    expect(commands.single.$1, endsWith('initdb.exe'));
    expect(commands.single.$2, contains('-D'));
    expect(commands.single.$2, contains(layout.postgresqlDataDirectory));

    final conf = File(layout.postgresqlConfigPath).readAsStringSync();
    expect(RegExp(r'port\s*=\s*5433').hasMatch(conf), isTrue);
    expect(
      RegExp(r"listen_addresses\s*=\s*'127\.0\.0\.1'").hasMatch(conf),
      isTrue,
    );

    await provisioner.install(release);
    expect(commands, hasLength(1));
    expect(result.activated, isTrue);
  });

  test('keeps installing after one component fails', () async {
    final report = await createProvisioner(
      installArchive: (component, archivePath, installName) async {
        if (component == StackComponent.mysql) {
          throw const ProvisionException('database download is unavailable');
        }
        return createInstall(component, installName);
      },
    ).installAll([ComponentCatalog.mariadb, ComponentCatalog.php]);

    expect(report.ok, isFalse);
    expect(report.failures, hasLength(1));
    expect(report.failures.single.release, ComponentCatalog.mariadb);
    expect(report.installed, hasLength(1));
    expect(report.installed.single.release, ComponentCatalog.php);
  });

  test('reuses an installed version instead of downloading it again', () async {
    final release = ComponentCatalog.nodejs;
    createInstall(release.component, release.installName);
    installCalls.clear();
    var downloads = 0;

    final provisioner = StackProvisioner(
      layout,
      download: (uri, file, onProgress) async {
        downloads++;
      },
      digest: (_) async => release.sha256,
      installArchive: (component, archivePath, installName) async {
        installCalls.add(component);
        return createInstall(component, installName);
      },
    );

    final result = await provisioner.install(release);

    expect(result.alreadyInstalled, isTrue);
    expect(downloads, 0);
    expect(installCalls, isEmpty);
    expect(
      StackLayout.detect(layout.root)!.activeVersion(StackComponent.nodejs),
      isNotNull,
    );
  });

  test('keeps a generated config when a component is re-checked', () async {
    final release = ComponentCatalog.redis;
    final provisioner = createProvisioner();
    final first = await provisioner.install(release);
    final config = File(p.join(first.install.directory, 'redis.conf'));

    // Simulate a user edit and re-run provisioning for the same version.
    config.writeAsStringSync('${config.readAsStringSync()}\nmaxmemory 64mb\n');
    await provisioner.install(release);

    expect(config.readAsStringSync(), contains('maxmemory 64mb'));
  });

  test('installs a bundled archive without contacting the network', () async {
    final release = ComponentCatalog.php;
    final payloadDirectory = Directory(p.join(temp.path, 'payload'))
      ..createSync(recursive: true);
    File(
      p.join(payloadDirectory.path, 'php.zip'),
    ).writeAsStringSync('bundled php archive');
    File(p.join(payloadDirectory.path, BundledPayload.manifestName))
        .writeAsStringSync(
          jsonEncode({
            'schema': 1,
            'components': [
              {
                'id': release.id,
                'file': 'php.zip',
                'sha256': release.sha256,
              },
            ],
          }),
        );
    final payload = BundledPayload.load(payloadDirectory)!;

    final provisioner = StackProvisioner(
      layout,
      payload: payload,
      download: (uri, file, onProgress) async {
        fail('a bundled component must not be downloaded');
      },
      digest: (_) async => release.sha256,
      installArchive: (component, archivePath, installName) async {
        expect(archivePath, p.join(payloadDirectory.path, 'php.zip'));
        return createInstall(component, installName);
      },
    );
    final progress = <ProvisionProgress>[];

    final result = await provisioner.install(release, onProgress: progress.add);

    expect(result.install.version, release.installName);
    expect(
      progress.map((entry) => entry.phase),
      isNot(contains(ProvisionPhase.downloading)),
    );
    expect(
      progress.any(
        (entry) => entry.message?.contains('bundled') ?? false,
      ),
      isTrue,
    );
  });
}
