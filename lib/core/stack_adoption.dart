import 'dart:io';

import 'package:path/path.dart' as p;

import 'ini.dart';
import 'stack_editor.dart';
import 'stack_layout.dart';

/// Result of adopting a stack that another tool created.
class AdoptionResult {
  const AdoptionResult({required this.layout, required this.warnings});

  final StackLayout layout;

  /// Problems that did not stop adoption, such as a component whose config
  /// could not be rewritten. The stack is still usable.
  final List<String> warnings;
}

class StackAdoptionException implements Exception {
  const StackAdoptionException(this.message);

  final String message;

  @override
  String toString() => message;
}

/// Takes ownership of an existing Laragon stack without moving its files.
///
/// Adoption writes `usr/stackpilot.ini` next to `usr/laragon.ini` and leaves
/// the Laragon marker in place. StackPilot then regenerates the configs it
/// owns (Apache, the launcher, PHP module) and selects the versions Laragon
/// had active. Laragon can still open the same folder because the original
/// marker is kept and kept in sync.
class StackAdoption {
  const StackAdoption._();

  /// Components in the order their configs are rewritten.
  ///
  /// PHP comes first because its Apache module and `php.ini` are shared with
  /// the other components; Apache last among the servers because its config
  /// includes the PHP module.
  static const List<StackComponent> _activationOrder = [
    StackComponent.php,
    StackComponent.nodejs,
    StackComponent.apache,
    StackComponent.nginx,
    StackComponent.mysql,
    StackComponent.postgresql,
    StackComponent.redis,
    StackComponent.memcached,
    StackComponent.mailpit,
  ];

  static AdoptionResult adopt(String root, {DateTime? now}) {
    final resolved = p.normalize(root.trim());
    if (resolved.isEmpty) {
      throw const StackAdoptionException('Choose a stack folder to adopt.');
    }

    final layout = StackLayout.detect(resolved);
    if (layout == null) {
      throw StackAdoptionException(
        'No stack was found in $resolved. A stack needs a usr folder with '
        'laragon.ini or stackpilot.ini and a bin folder.',
      );
    }
    if (layout.flavor != StackFlavor.laragon) {
      throw StackAdoptionException(
        'The stack in $resolved is already managed by '
        '${layout.flavor.label}.',
      );
    }

    final laragonMarker = File(p.join(resolved, 'usr', 'laragon.ini'));
    final marker = File(p.join(resolved, 'usr', 'stackpilot.ini'));
    final timestamp = (now ?? DateTime.now()).toUtc().toIso8601String();
    final warnings = <String>[];

    try {
      final raw = laragonMarker.readAsStringSync();
      final source = raw.startsWith('\uFEFF') ? raw.substring(1) : raw;
      final editor = IniEditor.parse(source)
        ..setValue('stackpilot', 'AdoptedFrom', 'laragon')
        ..setValue('stackpilot', 'AdoptedAt', timestamp);
      marker.parent.createSync(recursive: true);
      marker.writeAsStringSync(editor.serialize());
    } on FileSystemException catch (error) {
      throw StackAdoptionException(
        'Could not write ${marker.path}: ${error.message}',
      );
    }

    final adopted = StackLayout.detect(resolved);
    if (adopted == null || adopted.flavor != StackFlavor.stackpilot) {
      throw const StackAdoptionException(
        'The stack could not be read after adoption. Check that usr and bin '
        'are readable.',
      );
    }

    final editor = StackEditor(adopted);
    for (final component in _activationOrder) {
      // Read the active version from the Laragon view first. Writing
      // `usr/stackpilot.ini` switches detection to the StackPilot flavor, which
      // no longer consults Laragon's launcher PATH, so versions that only the
      // launcher identified would otherwise be lost.
      final install = _selectable(
        layout.activeVersion(component) ?? adopted.activeVersion(component),
        adopted.installedVersions(component),
        component,
        warnings,
      );
      if (install == null) {
        continue;
      }
      try {
        editor.selectVersion(component, install);
      } on StackEditException catch (error) {
        warnings.add('${_label(component)}: ${error.message}');
      }
    }

    // The Apache template is generated by selectVersion, but run it once more
    // after every marker change so includes and SSL reflect the final state.
    try {
      editor.refreshApacheConfig();
    } on StackEditException catch (error) {
      warnings.add('Apache: ${error.message}');
    }

    return AdoptionResult(
      layout: StackLayout.detect(resolved) ?? adopted,
      warnings: warnings,
    );
  }

  /// The version Laragon had active, or the newest installed version.
  static StackInstall? _selectable(
    StackInstall? active,
    List<StackInstall> installed,
    StackComponent component,
    List<String> warnings,
  ) {
    if (active != null) {
      return active;
    }

    if (installed.isEmpty) {
      return null;
    }
    final fallback = installed.last;
    warnings.add(
      '${_label(component)} ${fallback.displayVersion} was selected because '
      'the Laragon stack had no active version for it.',
    );
    return fallback;
  }

  static String _label(StackComponent component) {
    final name = component.directoryName;
    return name.isEmpty ? name : name[0].toUpperCase() + name.substring(1);
  }
}
